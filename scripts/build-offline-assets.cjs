// Regenerate after adding an application resource. No private data or server code.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const assets = new Set(['./index.html', './offline.html', './manifest.webmanifest']);
function scan(dir) {
  for (const entry of fs.readdirSync(path.join(root, dir), {withFileTypes:true})) {
    const name = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!['tests', 'scripts', 'supabase', '.git'].includes(entry.name)) scan(name);
    } else if (/\.(js|css|json|svg|png|webp|jpg|jpeg|woff2?|pdf)$/i.test(name)
      && !['service-worker.js', 'offline-assets.js'].includes(name)) assets.add('./' + name);
  }
}
for (const name of fs.readdirSync(root)) if (/\.(js|css)$/.test(name) && !['service-worker.js','offline-assets.js'].includes(name)) assets.add('./'+name);
for (const dir of ['pwa','styles','assets','icons','content','bac_referentiels']) if (fs.existsSync(path.join(root,dir))) scan(dir);
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
for (const [,url] of html.matchAll(/(?:src|href)="([^"#]+)"/g)) {
  if (!/^(https?:|data:|\/)/.test(url) && fs.existsSync(path.join(root,url.split('?')[0]))) assets.add('./'+url.replace(/^\.\//,''));
}
fs.writeFileSync(path.join(root,'offline-assets.js'), '/* Generated by scripts/build-offline-assets.cjs. Public application files only. */\nself.EPS_OFFLINE_ASSETS = '+JSON.stringify([...assets].sort(),null,2)+';\n');
console.log(`${assets.size} public resources in the offline manifest`);
